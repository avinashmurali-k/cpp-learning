#include <iostream>
using namespace std;

int main() {

    // Basic for loop
    for (int i = 1; i <= 5; i++) {
        cout << i << endl;
    }

    // Using a for loop with an array
    int nums[] = {1, 3, 5, 6, 8};

    for (int i = 0; i < 5; i++) {
        cout << nums[i] << endl;
    }

    return 0;
}
